#: Environment variables of the product that could leak a shell override into
#: the control groups. They are removed for every launched process.
PRODUCT_ENV_VARS = (
    "JELLYFIN_URL",
    "LISTEN_HOST",
    "LISTEN_PORT",
    "BYPASS_CLIENTS",
    "PLAYBACK_BYPASS_CLIENTS",
    "PLAYBACK_CACHE_BYPASS_CLIENTS",
    "VIDEO_BYPASS_CLIENTS",
    "DEBUG",
    "REQUEST_TIMEOUT_SECONDS",
    "PLAYBACK_INFO_CACHE_ENABLED",
    "PLAYBACK_INFO_CACHE_TTL_SECONDS",
    "PLAYBACK_INFO_CACHE_MAX_ENTRIES",
    "LOG_LEVEL",
    "LOG_FILE",
    "ACCESS_LOG_FILE",
)


def proxy_config(
    *,
    upstream_url: str,
    port: int,
    profile: str,
    log_dir: Path,
    cache_enabled: bool,
) -> dict[str, Any]:
    """Isolated proxy TOML for one control group.

    ``profile`` selects the client-bypass matrix. Both groups use exactly the
    same matrix; only the cache switch differs.
    """

    matrices = {
        "matrix": {
            "bypass_clients": ["GlobalClient"],
            "playback_bypass_clients": ["PlaybackOnly"],
            "video_bypass_clients": ["VideoOnly"],
            "playback_cache_bypass_clients": ["CacheOnly"],
        },
        "matrix_overlap": {
            "bypass_clients": ["GlobalClient"],
            "playback_bypass_clients": ["PlaybackOnly", "OverlapClient"],
            "video_bypass_clients": ["VideoOnly", "OverlapClient"],
            "playback_cache_bypass_clients": ["CacheOnly"],
        },
    }
    if profile not in matrices:
        raise ValidationError(f"unknown bypass profile {profile!r}")
    config: dict[str, Any] = {
        "jellyfin_url": upstream_url,
        "listen_host": "127.0.0.1",
        "listen_port": port,
        "debug": False,
        "request_timeout_seconds": 60,
        "log_level": "INFO",
        "log_file": str(log_dir / "proxy.log"),
        "access_log_file": str(log_dir / "access.log"),
        "playback_info_cache_ttl_seconds": 21600,
        "playback_info_cache_max_entries": 4096,
        **matrices[profile],
    }
    config["playback_info_cache_enabled"] = cache_enabled
    return config


def toml_dumps(values: Mapping[str, Any]) -> str:
    """Serialize the small, flat configuration subset used by the tool."""

    lines = ["# generated by scripts/validate_jellyfin_12_3.py -- do not edit"]
    for key, value in values.items():
        lines.append(f"{key} = {_toml_value(value)}")
    return "\n".join(lines) + "\n"


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(json.dumps(str(item)) for item in value) + "]"
    return json.dumps(str(value))


def clean_environment(extra: Mapping[str, str] | None = None) -> dict[str, str]:
    env = {key: value for key, value in os.environ.items() if key not in PRODUCT_ENV_VARS}
    # Never let a developer PYTHONPATH inject modules into the control group.
    env.pop("PYTHONPATH", None)
    env["PYTHONUNBUFFERED"] = "1"
    if extra:
        env.update({key: str(value) for key, value in extra.items()})
    return env


@dataclass
class ManagedProcess:
    name: str
    argv: list[str]
    cwd: Path
    env: dict[str, str]
    port: int
    log_path: Path
    process: subprocess.Popen[bytes] | None = None

    def start(self) -> None:
        if port_is_open(self.port):
            raise ValidationError(
                f"port {self.port} for {self.name} is already in use; refusing to reuse an unknown process"
            )
        ensure_directory(self.log_path.parent, 0o700)
        handle = self.log_path.open("ab")
        self.process = subprocess.Popen(
            self.argv,
            cwd=str(self.cwd),
            env=self.env,
            stdout=handle,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        handle.close()

    @property
    def pid(self) -> int | None:
        return self.process.pid if self.process else None

    def wait_ready(self, *, timeout: float = 90, probe_path: str = "/System/Info/Public") -> None:
        if self.port <= 0:
            return

        def _ready() -> bool:
            if self.process is not None and self.process.poll() is not None:
                raise ValidationError(
                    f"{self.name} exited with code {self.process.returncode}; see {self.log_path}"
                )
            try:
                response = httpx.get(
                    f"http://127.0.0.1:{self.port}{probe_path}", timeout=2, follow_redirects=False
                )
            except httpx.HTTPError:
                return False
            return response.status_code < 500

        wait_for(_ready, timeout=timeout, interval=0.5, description=f"{self.name} readiness")

    def log_size(self) -> int:
        return self.log_path.stat().st_size if self.log_path.exists() else 0

    def read_log(self, *, from_offset: int = 0) -> str:
        if not self.log_path.exists():
            return ""
        with self.log_path.open("rb") as handle:
            handle.seek(from_offset)
            return handle.read().decode("utf-8", "replace")

    def stop(self, *, timeout: float = 15) -> None:
        if self.process is None:
            return
        if self.process.poll() is not None:
            self.process = None
            return
        self.process.terminate()
        try:
            self.process.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            self.process.kill()
            self.process.wait(timeout=timeout)
        self.process = None


@dataclass
class LaunchPlan:
    group: str
    config_path: Path
    log_dir: Path
    process: ManagedProcess
    config: dict[str, Any] = field(default_factory=dict)


class ProcessSupervisor:
    """Owns every process launched for this run and guarantees cleanup."""

    def __init__(self, paths: RunPaths) -> None:
        self.paths = paths
        self._processes: list[ManagedProcess] = []
        self._registrations: list[dict[str, Any]] = []

    def launch(
        self,
        name: str,
        argv: list[str],
        *,
        cwd: Path,
        env: dict[str, str],
        port: int,
        log_path: Path,
    ) -> ManagedProcess:
        process = ManagedProcess(
            name=name,
            argv=argv,
            cwd=cwd,
            env=env,
            port=port,
            log_path=log_path,
        )
        process.start()
        self._processes.append(process)
        self._registrations.append(
            {
                "name": name,
                "pid": process.pid,
                "argv": argv,
                "cwd": str(cwd),
                "port": port,
                "log": str(log_path),
                "started_at": utc_now(),
            }
        )
        return process

    def stop_all(self) -> list[str]:
        actions: list[str] = []
        for process in reversed(self._processes):
            pid = process.pid
            process.stop()
            if pid is not None:
                actions.append(f"stopped {process.name} pid={pid}")
        self._processes.clear()
        return actions

    def registrations(self) -> list[dict[str, Any]]:
        return list(self._registrations)


def launch_proxy(
    supervisor: ProcessSupervisor,
    paths: RunPaths,
    *,
    group: str,
    port: int,
    upstream_url: str,
    cache_enabled: bool,
    profile: str = "matrix",
) -> LaunchPlan:
    source_dir = paths.proxy / group
    config_dir = ensure_directory(paths.proxy / group / "config", 0o700)
    if not (source_dir / "main.py").is_file():
        raise ValidationError(f"extracted product source missing at {source_dir}")
    config = proxy_config(
        upstream_url=upstream_url,
        port=port,
        profile=profile,
        log_dir=config_dir,
        cache_enabled=cache_enabled,
    )
    config_path = config_dir / "JellyfinProxy.toml"
    write_text(config_path, toml_dumps(config), mode=0o600)
    process = supervisor.launch(
        group,
        [str(repo_root() / ".venv" / "bin" / "python"), "main.py", "--config", str(config_path)],
        cwd=source_dir,
        env=clean_environment(),
        port=port,
        log_path=config_dir / f"{group}.out.log",
    )
    process.wait_ready(timeout=120)
    return LaunchPlan(group=group, config_path=config_path, log_dir=config_dir, process=process, config=config)


def launch_observatory(
    supervisor: ProcessSupervisor,
    paths: RunPaths,
    *,
    port: int,
    target_url: str,
) -> ManagedProcess:
    log_dir = ensure_directory(paths.observatory, 0o700)
    env = clean_environment(
        {
            "S1_OBS_TARGET": target_url,
            "S1_OBS_LOG": str(log_dir / "observatory.jsonl"),
            "S1_OBS_MAX_JSON": "65536",
        }
    )
    process = supervisor.launch(
        "observatory",
        [
            str(repo_root() / ".venv" / "bin" / "python"),
            "-m",
            "uvicorn",
            "scripts.validation.observatory:app",
            "--host",
            "127.0.0.1",
            "--port",
            str(port),
            "--log-level",
            "warning",
        ],
        cwd=repo_root(),
        env=env,
        port=port,
        log_path=log_dir / "observatory.out.log",
    )
    process.wait_ready(timeout=90, probe_path="/__s1/control")
    return process


def set_observatory_group(port: int, group: str) -> None:
    response = httpx.post(f"http://127.0.0.1:{port}/__s1/control", json={"group": group}, timeout=10)
    if response.status_code != 200:
        raise ValidationError(f"failed to set observatory group: {response.status_code}")


def observatory_group(port: int) -> str:
    response = httpx.get(f"http://127.0.0.1:{port}/__s1/control", timeout=10)
    return str(response.json().get("group"))


def wait_port_closed(port: int, *, timeout: float = 30) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if not port_is_open(port):
            return True
        time.sleep(0.3)
    return False


def free_port_in_range(start: int, end: int) -> int:
    for port in range(start, end + 1):
        if not port_is_open(port):
            return port
    raise ValidationError(f"no free port in {start}-{end}")
