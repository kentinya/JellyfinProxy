"""Start/stop the control-group processes for the real Jellyfin baseline.

Groups:
  J     -- direct Jellyfin (no proxy; nothing to launch)
  O     -- transparent observatory in front of Jellyfin
  B-on  -- fixed Slice Base product with the original JSON cache enabled
  B-off -- same product source with only the JSON cache disabled

Every process is launched from the run directory with an explicitly filtered
environment so that a developer shell override cannot change the controls.
"""

